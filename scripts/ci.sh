#!/usr/bin/env bash
# scripts/ci.sh — run every linter and test in one command: a tracked-file
# length gate, a duplicate-migration-version gate, rustfmt, Clippy, the test
# suite, and rustdoc. These are the same checks
# .github/workflows/ci.yml runs on every push (it calls this script), so a
# clean run here is a green pipeline there.
#
# Every check runs even after another has already failed, so one pass
# reports everything that is broken at once.
#
# Within a check, Cargo is told not to stop at the first failure either:
# `--keep-going` (Clippy and rustdoc) keeps building every crate and target
# that does not depend on the broken one (so a compile error in one target does
# not hide errors in the others), and `--no-fail-fast` (`cargo test` has no
# `--keep-going`) runs every test binary even after one fails.
#
# The exit status is explicit: 0 when every check ran clean, 1 when any of
# them failed — never some other code, and never merely the last step's
# status leaking out.
#
# `--locked` makes Cargo fail instead of silently updating Cargo.lock, so a
# stale lockfile is caught here rather than drifting in CI.
#
# The output is terse: it reports what is broken and little else, because
# its main reader is an agent paying for every line. A clean run prints one
# header per check, one test tally and the verdict. To that end:
#
# - every Cargo command runs with `--quiet`, dropping the Compiling,
#   Checking, Running and Finished status lines but keeping every diagnostic;
# - rustfmt names the files that need formatting instead of printing a diff
#   (the fix is always `cargo fmt`);
# - the test build reports compiler errors one line each
#   (`--message-format short`): Clippy has already printed them in full with
#   their suggestions, since it checks the same targets;
# - libtest's per-test progress, `running N tests` and passing `test result`
#   lines are filtered out (see filter_test_output); failures, their
#   captured output and the failing summary lines come through untouched;
# - Clippy and rustdoc diagnostics lose their per-lint documentation link
#   and `#[allow(...)]` advice (see without_lint_boilerplate).
#
# Usage:
#
#   scripts/ci.sh    # run the whole gate

set -uo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(dirname -- "$script_dir")"
cd "$repo_root" || exit 1

# Make the Rust toolchain findable even when this runs from a non-login shell:
# rustup installs into ~/.cargo/bin and exports it only from shell profile
# files, which such shells never source. Fail loudly rather than reporting
# every check as broken when the toolchain is genuinely absent.
if ! command -v cargo >/dev/null 2>&1; then
  if [[ -f "${HOME:-}/.cargo/env" ]]; then
    . "$HOME/.cargo/env"
  fi
  if ! command -v cargo >/dev/null 2>&1 && [[ -x "${HOME:-}/.cargo/bin/cargo" ]]; then
    PATH="$HOME/.cargo/bin:$PATH"
  fi
  if ! command -v cargo >/dev/null 2>&1; then
    printf 'cargo not found on PATH; install the Rust toolchain (rustup)\n' >&2
    exit 1
  fi
fi

# The database tests (`#[sqlx::test]`) need a reachable PostgreSQL whose role may
# create databases. Default to the local dev database from .env.example so the
# gate also works in worktrees and non-login shells; an exported DATABASE_URL
# (CI sets one) wins.
export DATABASE_URL="${DATABASE_URL:-postgres://wired:wired@localhost:5432/wired}"

failed_checks=()

# step LABEL COMMAND... — print the label, stream the command's own output
# through untouched, and remember the label when the command fails.
step() {
  local label="$1"
  shift
  printf '==> %s\n' "$label"
  if ! "$@"; then
    failed_checks+=("$label")
    printf 'FAILED: %s\n' "$label" >&2
  fi
}

# check_file_lengths — no tracked file may exceed max_file_lines.
#
# Enumerates tracked files with `git ls-files`, so target/, .git/ and
# untracked scratch files are never counted and CI sees exactly what is
# committed. Offenders print one per line, longest first; a clean run
# prints nothing.
#
# The exemption list is NOT a loophole: a path may join it only with the
# same justification as Cargo.lock — generated by a tool, never
# hand-edited, so its length says nothing about code quality. The fix for
# any other failure is to split the file into submodules.
check_file_lengths() {
  local max_file_lines=1000
  local -a exemptions=(
    'Cargo.lock' # generated by Cargo, never hand-edited
  )

  local path e n exempt
  local -a offenders=()
  while IFS= read -r -d '' path; do
    [[ -f "$path" ]] || continue
    exempt=no
    for e in "${exemptions[@]}"; do
      if [[ "$path" == "$e" ]]; then
        exempt=yes
        break
      fi
    done
    [[ "$exempt" == yes ]] && continue
    # Skip binary files: `grep -I` never matches them, and a line count
    # means nothing for their contents anyway.
    grep -Iq . -- "$path" || continue
    n=$(wc -l < "$path")
    if ((n > max_file_lines)); then
      offenders+=("$n	$path")
    fi
  done < <(git ls-files -z)

  if ((${#offenders[@]} == 0)); then
    return 0
  fi
  printf '%s\n' "${offenders[@]}" | sort -t$'\t' -k1,1rn |
    while IFS=$'\t' read -r n path; do
      printf '%s: %s lines (limit %s)\n' "$path" "$n" "$max_file_lines"
    done
  return 1
}

# check_migration_versions — no two files under migrations/ may share a
# version (the digits before the first underscore). sqlx records each
# version once, so a duplicate fails every database setup with a
# `_sqlx_migrations_pkey` violation. Each branch is clean on its own; the
# collision appears once two branches that hand-picked the same version
# both land, so this check names the files instead of leaving the test
# suite to fail in every database-backed test.
check_migration_versions() {
  local duplicates
  duplicates=$(git ls-files -- 'migrations/*.sql' | sed -E 's#^migrations/([0-9]+)_.*#\1#' |
    sort | uniq -d)
  [[ -z "$duplicates" ]] && return 0

  local version
  while IFS= read -r version; do
    printf 'migration version %s is used by:\n' "$version"
    git ls-files -- "migrations/${version}_*" | sed 's/^/  /'
  done <<< "$duplicates"
  printf 'keep one per version and move the rest to fresh versions from `sqlx migrate add`\n'
  return 1
}

# check_formatting — rustfmt in check mode, naming each misformatted file
# rather than printing its diff.
check_formatting() {
  if cargo fmt --all --check -- --files-with-diff; then
    return 0
  fi
  printf 'run `cargo fmt` to fix the files above\n'
  return 1
}

# filter_test_output — drop libtest's noise from a `cargo test --quiet`
# stream on stdin, keeping everything that explains a failure.
#
# Dropped: `running N tests`, the progress lines of one character per test
# (`.`, `i`, `F`, with an optional `N/M` count), and every `test result: ok.`
# line. libtest writes a `has been running for over 60 seconds` warning
# straight after the progress characters on the same line, so those are cut
# off the front of it. Runs of blank lines collapse to one. Every other line passes through:
# the `failures:` sections with each failing test's captured output, a
# `test result: FAILED.` line, Cargo's errors and slow-test warnings. At the
# end, one line tallies the results of every test binary that ran.
#
# Lines are flushed as they come so CI still streams the step's output.
filter_test_output() {
  awk '
    function tally(i) {
      for (i = 1; i < NF; i++) {
        if ($(i + 1) ~ /^passed;/) passed += $i
        else if ($(i + 1) ~ /^failed;/) failed += $i
        else if ($(i + 1) ~ /^ignored;/) ignored += $i
      }
      seen = 1
    }
    /^[.iF]+test / { sub(/^[.iF]+/, "") }
    /^running [0-9]+ tests?$/ { next }
    /^[.iF]+( [0-9]+\/[0-9]+)?$/ { next }
    /^test result: ok\./ { tally(); next }
    /^test result: / { tally() }
    /^[[:space:]]*$/ { if (printed && !blank) { print ""; blank = 1 }; fflush(); next }
    { print; printed = 1; blank = 0; fflush() }
    END {
      if (seen) printf "tests: %d passed, %d failed, %d ignored\n", passed, failed, ignored
    }
  '
}

# run_tests — the whole suite, quiet, through filter_test_output, returning
# Cargo's own exit status rather than the filter's.
run_tests() {
  cargo test --quiet --locked --no-fail-fast --all-targets --all-features \
    --message-format short 2>&1 | filter_test_output
  return "${PIPESTATUS[0]}"
}

# without_lint_boilerplate COMMAND... — run a Clippy or rustdoc command and
# drop two `= help:` lines its diagnostics repeat under every lint: the
# documentation link, and the advice to add `#[allow(...)]`, which AGENTS.md
# forbids. The lint's name still shows in its `= note:` line. Returns the
# command's exit status, not the filter's.
without_lint_boilerplate() {
  "$@" 2>&1 |
    grep --line-buffered -vE '^ *= help: (for further information visit |to override )'
  return "${PIPESTATUS[0]}"
}

step 'file length' check_file_lengths
step 'migration versions' check_migration_versions
step 'rustfmt' check_formatting
step 'Clippy' without_lint_boilerplate \
  cargo clippy --quiet --locked --keep-going --all-targets --all-features
step 'tests' run_tests
step 'rustdoc' without_lint_boilerplate env RUSTDOCFLAGS='-D warnings' \
  cargo doc --quiet --locked --keep-going --no-deps --all-features

# Exit explicitly: green means 0, anything else means 1.
printf '\n'
if ((${#failed_checks[@]} == 0)); then
  printf 'All checks passed.\n'
  exit 0
fi

printf 'Failed checks:\n'
for check in "${failed_checks[@]}"; do
  printf '  - %s\n' "$check"
done
exit 1
