#!/usr/bin/env bash
# scripts/ci.sh — run every linter and test in one command: a tracked-file
# length gate, rustfmt, Clippy, the test suite, and rustdoc. These are the same checks
# .github/workflows/ci.yml runs on every push (it calls this script), so a
# clean run here is a green pipeline there.
#
# Every check runs even after another has already failed, so one pass
# reports everything that is broken at once.
#
# Within a check, Cargo is told not to stop at the first failure either:
# `--keep-going` keeps building every crate and target that does not depend on
# the broken one (so a compile error in one target does not hide errors in the
# others; `cargo test` has no such flag), and `--no-fail-fast` runs every test
# binary even after one fails.
#
# The exit status is explicit: 0 when every check ran clean, 1 when any of
# them failed — never some other code, and never merely the last step's
# status leaking out.
#
# `--locked` makes Cargo fail instead of silently updating Cargo.lock, so a
# stale lockfile is caught here rather than drifting in CI.
#
# Usage:
#
#   scripts/ci.sh    # run the whole gate

set -uo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(dirname -- "$script_dir")"
cd "$repo_root" || exit 1

# Make the Rust toolchain findable even when this runs from a non-login shell:
# rustup installs into ~/.cargo/bin and exports it only from shell profile
# files, which such shells never source. Fail loudly rather than reporting
# every check as broken when the toolchain is genuinely absent.
if ! command -v cargo >/dev/null 2>&1; then
  if [[ -f "${HOME:-}/.cargo/env" ]]; then
    . "$HOME/.cargo/env"
  fi
  if ! command -v cargo >/dev/null 2>&1 && [[ -x "${HOME:-}/.cargo/bin/cargo" ]]; then
    PATH="$HOME/.cargo/bin:$PATH"
  fi
  if ! command -v cargo >/dev/null 2>&1; then
    printf 'cargo not found on PATH; install the Rust toolchain (rustup)\n' >&2
    exit 1
  fi
fi

# The database tests (`#[sqlx::test]`) need a reachable PostgreSQL whose role may
# create databases. Default to the local dev database from .env.example so the
# gate also works in worktrees and non-login shells; an exported DATABASE_URL
# (CI sets one) wins.
export DATABASE_URL="${DATABASE_URL:-postgres://wired:wired@localhost:5432/wired}"

failed_checks=()

# step LABEL COMMAND... — print the label, stream the command's own output
# through untouched, and remember the label when the command fails.
step() {
  local label="$1"
  shift
  printf '\n==> %s\n' "$label"
  if ! "$@"; then
    failed_checks+=("$label")
    printf 'FAILED: %s\n' "$label" >&2
  fi
}

# check_file_lengths — no tracked file may exceed max_file_lines.
#
# Enumerates tracked files with `git ls-files`, so target/, .git/ and
# untracked scratch files are never counted and CI sees exactly what is
# committed. Offenders print one per line, longest first; a clean run
# prints nothing.
#
# The exemption list is NOT a loophole: a path may join it only with the
# same justification as Cargo.lock — generated by a tool, never
# hand-edited, so its length says nothing about code quality. The fix for
# any other failure is to split the file into submodules.
check_file_lengths() {
  local max_file_lines=1000
  local -a exemptions=(
    'Cargo.lock' # generated by Cargo, never hand-edited
  )

  local path e n exempt
  local -a offenders=()
  while IFS= read -r -d '' path; do
    [[ -f "$path" ]] || continue
    exempt=no
    for e in "${exemptions[@]}"; do
      if [[ "$path" == "$e" ]]; then
        exempt=yes
        break
      fi
    done
    [[ "$exempt" == yes ]] && continue
    # Skip binary files: `grep -I` never matches them, and a line count
    # means nothing for their contents anyway.
    grep -Iq . -- "$path" || continue
    n=$(wc -l < "$path")
    if ((n > max_file_lines)); then
      offenders+=("$n	$path")
    fi
  done < <(git ls-files -z)

  if ((${#offenders[@]} == 0)); then
    return 0
  fi
  printf '%s\n' "${offenders[@]}" | sort -t$'\t' -k1,1rn |
    while IFS=$'\t' read -r n path; do
      printf '%s: %s lines (limit %s)\n' "$path" "$n" "$max_file_lines"
    done
  return 1
}

step 'file length' check_file_lengths
step 'rustfmt' cargo fmt --all --check
step 'Clippy' cargo clippy --locked --keep-going --all-targets --all-features
step 'tests' cargo test --locked --no-fail-fast --all-targets --all-features
step 'rustdoc' env RUSTDOCFLAGS='-D warnings' cargo doc --locked --keep-going --no-deps --all-features

# Exit explicitly: green means 0, anything else means 1.
printf '\n'
if ((${#failed_checks[@]} == 0)); then
  printf 'All checks passed.\n'
  exit 0
fi

printf 'Failed checks:\n'
for check in "${failed_checks[@]}"; do
  printf '  - %s\n' "$check"
done
exit 1
